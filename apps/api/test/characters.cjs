async function request(path,status,body,actor=0){
 const response=await fetch(`http://127.0.0.1:3106/${path}`,{method:body?'POST':'GET',headers:{...(actor===null?{}:{Cookie:`vtt_session=${cookies[actor]}`}),...(body&&!(body instanceof FormData)?{'Content-Type':'application/json'}:{})},body:body instanceof FormData?body:body?JSON.stringify(body):undefined})
 const data=await response.json();assert.equal(response.status,status,`${path}: ${JSON.stringify(data)}`);return data
}
function form(name,ownerId=owner,appearance,token){
 const data=new FormData();data.append('name',name);data.append('owner_id',ownerId);data.append('color','#a47ae2')
 if(appearance)data.append('appearance',new Blob([appearance],{type:'image/png'}),'aparencia.png')
 if(token)data.append('token',new Blob([token],{type:'image/png'}),'token.png')
 return data
}
async function asset(url,status,actor=0,bytes){
 const response=await fetch(`http://127.0.0.1:3106${url.replace(/^\/api/,'')}`,{headers:actor===null?{}:{Cookie:`vtt_session=${cookies[actor]}`}})
 assert.equal(response.status,status,url)
 if(bytes){assert.equal(response.headers.get('content-type'),'image/png');assert.deepEqual(Buffer.from(await response.arrayBuffer()),bytes)}
}
