async function contextFor(token) {
  const context = await browser.newContext({viewport:{width:1440,height:960}})
  await context.addCookies([{name:'vtt_session',value:token,domain:'127.0.0.1',path:'/',httpOnly:true,sameSite:'Lax'}])
  await context.route('**/api/**', async route=>{
    const url = new URL(route.request().url())
    const response = await route.fetch({url:`http://127.0.0.1:3104${url.pathname.replace(/^\/api/,'')}${url.search}`})
    await route.fulfill({response})
  })
  context.on('page',page=>page.on('pageerror',error=>errors.push(error.message)))
  return context
}
